import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';

const root = resolve(import.meta.dirname, '..');
const read = (file) => readFileSync(join(root, file), 'utf8');
const write = (file, contents) => {
  const path = join(root, file);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
};
const token = JSON.parse(read('tokens/fpe.tokens.json'));
const resolveColor = (value) => {
  const raw = value.$value;
  if (/^#[0-9a-fA-F]{6}$/.test(raw)) return raw.toUpperCase();
  const match = /^\{color\.([\w-]+)\}$/.exec(raw);
  if (!match || !token.color[match[1]]) throw new Error(`Unknown color alias: ${raw}`);
  return resolveColor(token.color[match[1]]);
};
const resolveGradient = (value) => value.$value.replace(/\{color\.([\w-]+)\}/g, (_, name) => {
  if (!token.color[name]) throw new Error(`Unknown gradient color: ${name}`);
  return resolveColor(token.color[name]);
});
const modes = ['light', 'dark'];
const shadcnKeys = Object.keys(token.semantic.light);
assert.deepEqual(shadcnKeys.sort(), Object.keys(token.semantic.dark).sort(), 'Light and dark semantic keys must match');
const css = [
  '/* Generated by scripts/build.mjs from tokens/fpe.tokens.json. Do not edit directly. */',
  ':root {',
  ...Object.entries(token.color).map(([name, val]) => `  --fpe-${name}: ${resolveColor(val)};`),
  ...Object.entries(token.gradient).map(([name, val]) => `  --fpe-gradient-${name}: ${resolveGradient(val)};`),
  '  --fpe-gradient-text: var(--fpe-gradient-ink-light);',
  ...Object.entries(token.semantic.light).map(([name, val]) => `  --${name}: ${resolveColor(val)};`),
  `  --radius: ${token.radius.base.$value};`,
  ...Object.entries(token.spacing).map(([name, val]) => `  --fpe-space-${name}: ${val.$value};`),
  ...Object.entries(token.radius).map(([name, val]) => `  --fpe-radius-${name}: ${val.$value};`),
  ...Object.entries(token.motion.duration).map(([name, val]) => `  --fpe-motion-${name}: ${val.$value};`),
  ...Object.entries(token.motion.easing).map(([name, val]) => `  --fpe-ease-${name}: cubic-bezier(${val.$value.join(', ')});`),
  ...Object.entries(token.typography.size).map(([name, val]) => `  --fpe-size-${name}: ${val.$value};`),
  ...Object.entries(token.typography.weight).map(([name, val]) => `  --fpe-weight-${name}: ${val.$value};`),
  ...Object.entries(token.typography.tracking).map(([name, val]) => `  --fpe-tracking-${name}: ${val.$value};`),
  ...Object.entries(token.typography.leading).map(([name, val]) => `  --fpe-leading-${name}: ${val.$value};`),
  `  --fpe-font-sans: ${token.typography.body.$value.map((name) => name.includes(' ') ? `"${name}"` : name).join(', ')};`,
  `  --fpe-font-mono: ${token.typography.display.$value.map((name) => name.includes(' ') ? `"${name}"` : name).join(', ')};`,
  '}',
  '.dark, [data-theme="dark"] {',
  '  --fpe-gradient-text: var(--fpe-gradient-ink-dark);',
  ...Object.entries(token.semantic.dark).map(([name, val]) => `  --${name}: ${resolveColor(val)};`),
  '}',
  '/* Tailwind CSS v4 and shadcn/ui semantic token bridge */',
  '@theme inline {',
  ...shadcnKeys.map((key) => `  --color-${key}: var(--${key});`),
  '  --font-sans: var(--fpe-font-sans);',
  '  --font-mono: var(--fpe-font-mono);',
  '  --radius-sm: calc(var(--radius) * 0.6);',
  '  --radius-md: calc(var(--radius) * 0.8);',
  '  --radius-lg: var(--radius);',
  '  --radius-xl: calc(var(--radius) * 1.4);',
  '  --color-fpe-pink-deep: var(--fpe-pink-deep);',
  '  --color-fpe-violet: var(--fpe-violet);',
  '  --color-fpe-pink-highlight: var(--fpe-pink-highlight);',
  '}',
  ''
].join('\n');
write('css/fpe-theme.css', css);
const registry = JSON.parse(read('registry.json'));
assert.equal(registry.name, 'fpe-design-system');
const theme = registry.items.find((i) => i.name === 'fpe-theme');
assert(theme, 'FPE theme registry item must exist');
for (const [name, value] of Object.entries(token.gradient)) {
  assert.equal(theme.css?.['@layer base']?.[':root']?.[`--fpe-gradient-${name}`], resolveGradient(value), `Gradient registry drift: ${name}`);
}
assert.equal(theme.css?.['@layer base']?.[':root']?.['--fpe-gradient-text'], 'var(--fpe-gradient-ink-light)');
assert.equal(theme.css?.['@layer base']?.['.dark']?.['--fpe-gradient-text'], 'var(--fpe-gradient-ink-dark)');
for (const mode of modes) {
  for (const [name, val] of Object.entries(token.semantic[mode])) {
    assert.equal(theme.cssVars[mode][name]?.toUpperCase(), resolveColor(val), `${mode}.${name} drift`);
  }
}
rmSync(join(root, 'dist'), { recursive: true, force: true });
mkdirSync(join(root, 'dist'), { recursive: true });
for (const file of ['index.html', 'styles.css', 'app.js']) cpSync(join(root, 'site', file), join(root, 'dist', file));
for (const file of ['fpe-theme.css', 'fpe-motion.css']) {
  cpSync(join(root, 'css', file), join(root, 'dist', 'css', file));
}
cpSync(join(root, 'assets', 'brand'), join(root, 'dist', 'assets', 'brand'), { recursive: true });
mkdirSync(join(root, 'dist', 'r'), { recursive: true });
for (const item of registry.items) {
  const expanded = structuredClone(item);
  expanded.$schema = 'https://ui.shadcn.com/schema/registry-item.json';
  if (expanded.files) {
    expanded.files = expanded.files.map((file) => ({ ...file, content: read(file.path) }));
  }
  write(`dist/r/${item.name}.json`, JSON.stringify(expanded, null, 2) + '\n');
}
write('dist/r/registry.json', JSON.stringify(registry, null, 2) + '\n');
console.log(`FPE build: ${shadcnKeys.length} semantic tokens/mode, ${registry.items.length} registry items, static docs ready`);

// Portable offline snapshot: CSS, JavaScript and brand SVGs embedded in one HTML.
const escaped = (value) => value.replaceAll('</style', '<\\/style').replaceAll('</script', '<\\/script');
let offline = read('site/index.html');
for (const stylesheet of ['css/fpe-theme.css', 'css/fpe-motion.css', 'styles.css']) {
  const original = `<link rel="stylesheet" href="${stylesheet}" />`;
  const source = stylesheet === 'styles.css' ? read('site/styles.css') : read(stylesheet);
  if (!offline.includes(original)) throw new Error(`Missing stylesheet link: ${stylesheet}`);
  offline = offline.replace(original, `<style>\n${escaped(source)}\n</style>`);
}
const scriptTag = '<script type="module" src="app.js"></script>';
if (!offline.includes(scriptTag)) throw new Error('Missing module script tag');
offline = offline.replace(scriptTag, '');
for (const variant of ['fpe-mark.svg', 'fpe-mark-gradient.svg', 'fpe-mark-white.svg', 'fpe-mark-black.svg']) {
  const resource = `assets/brand/${variant}`;
  const content = read(`assets/brand/${variant}`);
  const uri = `data:image/svg+xml;base64,${Buffer.from(content).toString('base64')}`;
  offline = offline.replaceAll(resource, uri);
}
offline = offline.replace('</body>', `<script>\n${escaped(read('site/app.js'))}\n</script>\n</body>`);
write('dist/offline.html', offline);
